# ========== 参数 ==========
d = 0.5 / 100    # 挡光片宽度 m
s = 50.0 / 100   # 光电门间距 m

# 数据格式：[t1a, t1b, t2a, t2b]，单位 ms
data = {
    "垫一个垫块": [
        [72.62, 66.63, 37.49, 36.67],
        [75.97, 69.00, 37.57, 36.70],
        [75.76, 68.90, 37.94, 37.07],
        [76.16, 69.47, 38.02, 37.18],
        [75.62, 68.94, 38.19, 37.32],
    ],
    "垫两个垫块": [
        [32.03, 29.21, 16.02, 15.65],
        [32.99, 30.10, 16.09, 15.68],
        [34.80, 32.24, 17.16, 16.68],
        [32.08, 29.37, 16.77, 16.31],
        [34.40, 30.93, 16.17, 15.76],
    ],
    "垫三个垫块": [
        [26.23, 23.83, 12.88, 12.57],
        [26.20, 23.83, 12.88, 12.57],
        [26.16, 23.78, 12.89, 12.59],
        [26.32, 23.93, 12.93, 12.62],
        [27.79, 24.98, 13.03, 12.72],
    ],
    "垫四个垫块": [
        [22.57, 20.52, 11.11, 10.85],
        [22.80, 20.69, 11.16, 10.88],
        [22.74, 20.67, 11.18, 10.92],
        [21.97, 20.09, 11.12, 10.87],
        [22.84, 20.77, 11.22, 10.96],
    ]
}


def calc_a(t1_ms, t2_ms):
    """
    t1_ms：光电门1遮光时间 ms
    t2_ms：光电门2遮光时间 ms
    返回 a (m/s²)
    """
    dt1 = t1_ms / 1000.0
    dt2 = t2_ms / 1000.0
    v1 = d / dt1
    v2 = d / dt2
    a = (v2**2 - v1**2) / (2 * s)
    return a, v1, v2, dt1, dt2


# 循环全部组别
for group_name, exp_list in data.items():
    print(f"\n==== {group_name} ====")
    a_sum = 0.0
    count = 0
    for idx, row in enumerate(exp_list):
        t1a, t1b, t2a, t2b = row

        a_a, v1a, v2a, dt1a, dt2a = calc_a(t1a, t2a)
        a_b, v1b, v2b, dt1b, dt2b = calc_a(t1b, t2b)

        a_avg_one = (a_a + a_b) / 2.0
        a_sum += a_avg_one
        count += 1

        print(f"第{idx+1}组：")
        print(f"  dt1a={dt1a*1000:.2f}ms, v1a={v1a:.4f} m/s；dt2a={dt2a*1000:.2f}ms, v2a={v2a:.4f} m/s  → a_a={a_a:.4f} m/s²")
        print(f"  dt1b={dt1b*1000:.2f}ms, v1b={v1b:.4f} m/s；dt2b={dt2b*1000:.2f}ms, v2b={v2b:.4f} m/s  → a_b={a_b:.4f} m/s²")
        print(f"  本组平均 a = {a_avg_one:.4f} m/s²  ({a_avg_one*100:.2f} cm/s²)\n")

    total_avg = a_sum / count
    print(f">>> {group_name} 总平均 a = {total_avg:.4f} m/s²  = {total_avg*100:.2f} cm/s²")
